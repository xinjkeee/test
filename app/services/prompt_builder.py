from __future__ import annotations

import json

from app.models.input import ProductInput

SYSTEM_PROMPT = """Ты — технический редактор B2B-каталогов.

Подготовь черновик карточки товара строго на основании объекта INPUT.
Ответ возвращай только в JSON, соответствующем переданной схеме.

КРИТИЧЕСКИЕ ПРАВИЛА:
1. Не добавляй технические характеристики, которых нет в INPUT.
2. Не придумывай числовые значения, диапазоны, размеры, единицы измерения,
   материалы, стандарты, интерфейсы, степень защиты, температуру или питание.
3. Не используй внешние знания о товаре, модели или производителе.
4. Не изменяй значения характеристик из INPUT. Переноси их дословно.
5. Если данных недостаточно, используй значение «данных нет» и внеси поле
   в missing_data.
6. Коммерческий блок должен опираться только на назначение и факты из INPUT.
   Если назначение неизвестно, прямо напиши, что данных недостаточно.
7. SEO-заголовок должен быть не длиннее 70 символов.
8. SEO-описание должно содержать от 800 до 1200 символов, включая пробелы.
9. Верни от 3 до 5 поисковых запросов без выдуманных технических свойств.
10. Все поля JSON обязательны, если они не имеют значения по умолчанию.
"""


def build_user_prompt(product: ProductInput, repair_message: str | None = None) -> str:
    payload = json.dumps(product.model_dump(exclude_none=True), ensure_ascii=False, indent=2)
    repair = ""
    if repair_message:
        repair = (
            "\nПредыдущий ответ не прошёл проверку. Исправь только перечисленные проблемы "
            "и верни полный JSON заново:\n" + repair_message + "\n"
        )
    return (
        "INPUT:\n"
        f"{payload}\n\n"
        "Сформируй SEO-заголовок, SEO-описание, полный список переданных характеристик, "
        "поисковые запросы, коммерческий блок и missing_data."
        f"{repair}"
    )
